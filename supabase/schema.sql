create table if not exists public.webhook_logs (
    id bigint generated by default as identity primary key,
    event_id text unique not null,
    borrower_name text not null,
    email text not null,
    phone text not null default '',
    loan_amount numeric(14, 2) not null check (loan_amount > 0),
    property_state text not null check (
        property_state in ('NSW', 'VIC', 'QLD', 'WA', 'SA', 'TAS', 'ACT', 'NT')
    ),
    referral_partner text not null default 'Direct',
    hubspot_deal_id text,
    status text not null check (status in ('PROCESSING', 'SUCCESS', 'FAILED')),
    error_message text,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create index if not exists webhook_logs_created_at_idx
    on public.webhook_logs (created_at desc);

alter table public.webhook_logs enable row level security;
revoke all on public.webhook_logs from anon, authenticated;
grant all on public.webhook_logs to service_role;
